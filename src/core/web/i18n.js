// Interface language. Source strings are English; RU maps them to Russian. Switching reloads the page,
// so labels built once at module load follow the chosen language too.

export const LANGUAGES = { en: 'English', ru: 'Русский' };

function stored() {
  try { return localStorage.getItem('lang'); } catch { return null; }
}

export const lang = LANGUAGES[stored()] ? stored() : 'en';
export const locale = lang === 'ru' ? 'ru-RU' : 'en-US';
document.documentElement.lang = lang;

const fill = (text, args) => text.replace(/\{(\d)\}/g, (_, i) => String(args[i] ?? ''));

export function t(key, ...args) {
  return fill((lang === 'ru' && RU[key]) || key, args);
}

// Plural forms are separated by "|": English "one|other", Russian "one|few|many". {0} is the count.
export function tp(key, n, ...args) {
  const forms = ((lang === 'ru' && RU[key]) || key).split('|');
  let form = n === 1 ? 0 : 1;
  if (lang === 'ru') {
    const d = n % 10;
    const h = n % 100;
    form = d === 1 && h !== 11 ? 0 : d >= 2 && d <= 4 && (h < 12 || h > 14) ? 1 : 2;
  }
  return fill(forms[Math.min(form, forms.length - 1)], [n, ...args]);
}

export function setLang(value) {
  try { localStorage.setItem('lang', value); } catch { /* storage unavailable */ }
  location.reload();
}

